# Spec 02 check 6: requests the committed set does not contain, generated from the IDs in the
# live database with a seeded random generator, so a run can be repeated. Each request picks:
#   package-ids:      a prefix of a random ID (random length), with random letters upper-cased
#   package-versions: a random ID, with random letters upper-cased
# plus a random includePrerelease (absent, true, false, yes) and semVerLevel (absent, 1.0.0, 2.0.0, 2).
# Lines already in recordings/requests.txt are dropped.
param([Parameter(Mandatory)] [int]$Seed, [int]$Count = 300, [Parameter(Mandatory)] [string]$OutFile)
. "$PSScriptRoot\common.ps1"
$random = New-Object System.Random $Seed
$ids = [string[]]@(Invoke-Sql -Database 'NuGetGallery' 'SELECT Id FROM dbo.PackageRegistrations' | ForEach-Object { $_.Id })
[Array]::Sort($ids, [StringComparer]::Ordinal)   # the generator's input order must not depend on the query plan
$committed = @{}
Get-Content (Join-Path $RepoRoot 'recordings\requests.txt') | ForEach-Object { $committed[$_.Trim()] = $true }

function Get-RandomCase([string]$Text) {
    return -join ($Text.ToCharArray() | ForEach-Object { if ($random.Next(4) -eq 0) { [char]::ToUpperInvariant($_) } else { $_ } })
}
function Get-Flag {
    $flags = @()
    $p = @($null, 'true', 'false', 'yes')[$random.Next(4)]
    $s = @($null, '1.0.0', '2.0.0', '2')[$random.Next(4)]
    if ($p) { $flags += "includePrerelease=$p" }
    if ($s) { $flags += "semVerLevel=$s" }
    return $flags
}

$lines = New-Object System.Collections.Generic.List[string]
$seen = @{}
while ($lines.Count -lt $Count) {
    $id = $ids[$random.Next($ids.Count)]
    $flags = @(Get-Flag)
    if ($random.Next(2) -eq 0) {
        $prefix = Get-RandomCase $id.Substring(0, 1 + $random.Next($id.Length))
        $query = @("partialId=$([uri]::EscapeDataString($prefix))") + $flags
        $line = "GET /api/v2/package-ids?$($query -join '&')"
    } else {
        $line = "GET /api/v2/package-versions/$([uri]::EscapeDataString((Get-RandomCase $id)))"
        if ($flags.Count) { $line += "?$($flags -join '&')" }
    }
    if ($committed.ContainsKey($line) -or $seen.ContainsKey($line)) { continue }
    $seen[$line] = $true
    $lines.Add($line)
}
Write-Utf8File $OutFile (@("# generated by random-requests.ps1 -Seed $Seed from $($ids.Count) IDs") + $lines)
Write-Summary "- random requests: $Count, seed $Seed, from $($ids.Count) IDs in the live database"
